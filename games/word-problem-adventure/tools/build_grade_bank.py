"""Compile authored grade stories into an offline script; validate every answer.

Source: # quest title | hint, followed by five rows:
stable ID | story | expected answer | unit | independent arithmetic check | reasoning
Only exact rational arithmetic is allowed in checks. No eval or runtime fetch.
"""
import ast
from fractions import Fraction
import json
import re
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]


def calculate(expression):
    def walk(node):
        if isinstance(node, ast.Constant) and type(node.value) in (int, float):
            return Fraction(str(node.value))
        if isinstance(node, ast.BinOp):
            left, right = walk(node.left), walk(node.right)
            if isinstance(node.op, ast.Add): return left + right
            if isinstance(node.op, ast.Sub): return left - right
            if isinstance(node.op, ast.Mult): return left * right
            if isinstance(node.op, ast.Div): return left / right
        raise ValueError(f"Unsupported arithmetic: {expression}")
    return walk(ast.parse(expression, mode="eval").body)


def build():
    grades = {}
    stories = set()
    ids = set()
    for grade in range(2, 6):
        quests, questions = [], []
        for line_no, line in enumerate((ROOT / f"data/grade-{grade}.txt").read_text(encoding="utf-8").splitlines(), 1):
            if not line.strip(): continue
            if line.startswith("# "):
                title, hint = line[2:].split(" | ")
                quests.append({"id": f"g{grade}-q{len(quests)+1:02}", "title": title, "hint": hint, "ids": []})
                continue
            parts = line.split("|")
            assert len(parts) == 6, (grade, line_no, "six fields required")
            qid, story, expected, unit, expression, reason = parts
            assert re.fullmatch(f"wpa-g{grade}-[0-9]{{3}}", qid) and qid not in ids, (grade, line_no, "stable unique ID")
            ids.add(qid)
            answer = Fraction(expected)
            assert calculate(expression) == answer, (grade, line_no, story, expected, calculate(expression))
            assert answer >= 0, (grade, line_no, "negative answer")
            assert story not in stories, (grade, line_no, "duplicate story")
            assert "?" in story and reason.endswith("."), (grade, line_no, "punctuation")
            assert 8 <= len(story.split()) <= 80, (grade, line_no, "story length")
            assert len(reason.split()) >= 3 and unit and quests, (grade, line_no, "reasoning")
            if grade < 4: assert answer.denominator == 1
            stories.add(story)
            quest = quests[-1]
            quest["ids"].append(qid)
            questions.append({"id": qid, "grade": grade, "questId": quest["id"],
                "text": story, "answer": float(answer), "answerText": expected,
                "unit": unit, "hint": quest["hint"], "explain": reason,
                "check": expression, "skill": quest["title"]})
        assert len(questions) == 100, (grade, len(questions))
        assert len(quests) == 20 and all(len(q["ids"]) == 5 for q in quests), (grade, "20 quests of 5")
        grades[str(grade)] = {"quests": quests, "questions": questions}
    return "/* Generated by tools/build_grade_bank.py. Edit data/grade-*.txt. */\nwindow.WPA_GRADES = " + json.dumps(grades, ensure_ascii=False, indent=2) + ";\n"


if __name__ == "__main__":
    output = build()
    target = ROOT / "grade-bank.js"
    if "--check" in sys.argv:
        assert target.read_text(encoding="utf-8") == output, "Run build_grade_bank.py to refresh the bank"
    else:
        target.write_text(output, encoding="utf-8")
    print("PASS: 400 distinct stories, 100 per grade, 80 five-story quests, all exact answer checks.")
